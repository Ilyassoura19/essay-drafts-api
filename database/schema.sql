-- Essay Drafts API: database schema
-- Run this once in the Supabase SQL Editor (or with psql) to create the table.

CREATE TABLE IF NOT EXISTS drafts (
  id          SERIAL PRIMARY KEY,                     -- 1, 2, 3... generated by PostgreSQL
  title       VARCHAR(200) NOT NULL,                  -- a draft must have a title
  content     TEXT         NOT NULL DEFAULT '',       -- the essay text itself
  word_count  INTEGER      NOT NULL DEFAULT 0,        -- calculated by the service layer
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),    -- set automatically on INSERT
  updated_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW()     -- refreshed by the repository on UPDATE
);

-- Security (Supabase): Supabase also exposes every table through its own public
-- Data API. Turning on Row Level Security with no policies closes that side door,
-- so the ONLY way in is through our Express API. Our server connects as the table
-- owner, which is not affected. On a plain PostgreSQL this line is harmless.
ALTER TABLE drafts ENABLE ROW LEVEL SECURITY;
